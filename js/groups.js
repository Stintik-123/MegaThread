/** Запасная группа: всё, что не попало ни в одну тематическую. */
export const FALLBACK_GROUP = { id: 'other', title: 'Другое', desc: '' };

/**
 * Раскладывает ресурсы категории по группам.
 * Каждый ресурс попадает ровно в одну группу — в первую подходящую.
 */
export function groupResources(catId, resources) {
  const defs = CATEGORY_GROUPS[catId] || [];
  const buckets = defs.map((g) => ({ ...g, items: [] }));
  const rest = [];

  for (const r of resources || []) {
    let placed = false;
    for (const bucket of buckets) {
      const tags = bucket.tags || [];
      if (tags.some((t) => (r.tags || []).includes(t))) {
        bucket.items.push(r);
        placed = true;
        break;
      }
    }
    if (!placed) rest.push(r);
  }

  // Ни одна тема не подошла — собираем всё в запасную групцию в конце.
  if (rest.length) buckets.push({ ...FALLBACK_GROUP, items: rest });

  return buckets;
}
